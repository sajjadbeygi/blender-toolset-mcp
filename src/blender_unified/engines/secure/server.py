@mcp.tool()
def get_viewport_screenshot(ctx: Context, max_size: int = 1000) -> Image:
    """
    Capture a screenshot of the current Blender 3D viewport.

    Parameters:
    - max_size: Maximum size in pixels for the largest dimension (default: 1000)

    Returns the screenshot as an Image.
    """
    try:
        blender = get_blender_connection()

        # Create a unique temp file path (avoid the predictable pid-based name).
        fd, temp_path = tempfile.mkstemp(prefix="blender_screenshot_", suffix=".png")
        os.close(fd)

        try:
            result = blender.send_command("get_viewport_screenshot", {
                "max_size": max_size,
                "filepath": temp_path,
                "format": "png"
            })

            if "error" in result:
                raise Exception(result["error"])

            if not os.path.exists(temp_path):
                raise Exception("Screenshot file was not created")

            # Read the file
            with open(temp_path, 'rb') as f:
                image_bytes = f.read()

            return Image(data=image_bytes, format="png")
        finally:
            try:
                os.remove(temp_path)
            except OSError:
                pass

    except Exception as e:
        logger.error(f"Error capturing screenshot: {str(e)}")
        raise Exception(f"Screenshot failed: {str(e)}")

