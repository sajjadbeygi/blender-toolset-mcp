class InvalidTokenError(Exception):
    """The addon rejected the auth token.

    Raised by ``BlenderConnection.send_command`` so callers can distinguish a
    stale/wrong token (recoverable: try the next token source or pairing)
    from transport errors.
    """


@dataclass
class BlenderConnection:
    host: str
    port: int
    sock: socket.socket | None = None  # Changed from 'socket' to 'sock' to avoid naming conflict
    token: str | None = None
    _lock: threading.Lock = field(default_factory=threading.Lock, repr=False, compare=False)

    def connect(self) -> bool:
        """Connect to the Blender addon socket server"""
        if self.sock:
            return True

        try:
            self.sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            self.sock.connect((self.host, self.port))
            logger.info(f"Connected to Blender at {self.host}:{self.port}")
            return True
        except Exception as e:
            logger.error(f"Failed to connect to Blender: {str(e)}")
            self.sock = None
            return False

    def disconnect(self):
        """Disconnect from the Blender addon"""
        if self.sock:
            try:
                self.sock.close()
            except Exception as e:
                logger.error(f"Error disconnecting from Blender: {str(e)}")
            finally:
                self.sock = None

    def request_pair_token(self) -> str | None:
        """Ask the addon for its auth token via loopback pairing.

        Only succeeds before the addon's first authenticated client and only
        from loopback; otherwise the addon refuses. Used as a zero-config
        first-time bootstrap. Does not disturb the socket on failure.
        """
        if not self.sock and not self.connect():
            return None
        command = {"type": "pair", "params": {}, "token": self.token}
        try:
            self.sock.sendall(json.dumps(command).encode("utf-8"))
            self.sock.settimeout(30.0)
            data = self.receive_full_response(self.sock)
            response = json.loads(data.decode("utf-8"))
        except Exception as e:
            logger.warning(f"Pairing request failed: {e}")
            return None
        if response.get("status") != "success":
            logger.warning(f"Pairing unavailable: {response.get('message')}")
            return None
        token = (response.get("result") or {}).get("token")
        if token:
            # A paired token is guaranteed valid; remember it for reconnects.
            token_store.save_token_cache(self.host, self.port, token)
        return token

    def receive_full_response(self, sock, buffer_size=8192):
        """Receive one length-prefixed frame (4-byte big-endian length + payload)."""
        sock.settimeout(180.0)
        header = self._recv_exact(sock, 4)
        if header is None:
            raise Exception("Connection closed before receiving any data")
        length = int.from_bytes(header, "big")
        if length > MAX_MESSAGE_BYTES:
            raise Exception(f"message too large: {length} bytes")
        payload = self._recv_exact(sock, length)
        if payload is None:
            raise Exception("Connection closed before receiving full response")
        logger.info(f"Received complete response ({length} bytes)")
        return payload

    @staticmethod
    def _recv_exact(sock, n):
        """Read exactly ``n`` bytes from ``sock``, or ``None`` if closed early."""
        chunks = []
        remaining = n
        while remaining > 0:
            chunk = sock.recv(min(8192, remaining))
            if not chunk:
                return None
            chunks.append(chunk)
            remaining -= len(chunk)
        return b"".join(chunks)

    def send_command(self, command_type: str, params: dict[str, Any] | None = None) -> dict[str, Any]:
        """Send a command to Blender and return the response.

        Serialized with a per-connection lock so concurrent MCP tools cannot
        interleave requests on the single socket.
        """
        with self._lock:
            return self._send_command(command_type, params)

    def _send_command(self, command_type: str, params: dict[str, Any] | None = None) -> dict[str, Any]:
        if not self.sock and not self.connect():
            raise ConnectionError("Not connected to Blender")

        command = {
            "type": command_type,
            "params": params or {},
            "token": self.token,
        }

        try:
            # Log the command being sent (avoid logging params which may contain sensitive data)
            logger.info(f"Sending command: {command_type}")

            # Send the command
            self.sock.sendall(json.dumps(command).encode('utf-8'))
            logger.info(f"Command sent, waiting for response...")

            # Set a timeout for receiving - use the same timeout as in receive_full_response
            self.sock.settimeout(180.0)  # Match the addon's timeout

            # Receive the response using the improved receive_full_response method
            response_data = self.receive_full_response(self.sock)
            logger.info(f"Received {len(response_data)} bytes of data")

            response = json.loads(response_data.decode('utf-8'))
            logger.info(f"Response parsed, status: {response.get('status', 'unknown')}")

            if response.get("status") == "error":
                message = response.get("message", "Unknown error from Blender")
                logger.error(f"Blender error: {message}")
                if "invalid token" in message.lower():
                    # Drop any cached token (self-healing after a
                    # "Reset token & re-pair" on the addon side) and raise a
                    # typed error so get_blender_connection can fall through
                    # to the next token source or loopback pairing.
                    token_store.invalidate_token_cache(self.host, self.port)
                    raise InvalidTokenError(
                        "Authentication failed: the token this MCP client sends does not match "
                        "the Blender addon's active token. All token sources (BLENDERMCP_TOKEN, "
                        "token file, cache, addon temp file) and loopback pairing are tried "
                        "automatically; if you still see this, set BLENDERMCP_TOKEN to the Token "
                        "shown in the BlenderMCP panel (empty/placeholder values are ignored) or "
                        "press 'Reset token & re-pair' in the addon. "
                        "Diagnose with: python test_connection.py <token>"
                    )
                raise Exception(message)

            # The token authenticated successfully - remember it (no-op if the
            # cache already holds this exact token) for future reconnects.
            if self.token:
                token_store.save_token_cache(self.host, self.port, self.token)
            return response.get("result", {})
        except socket.timeout:
            logger.error("Socket timeout while waiting for response from Blender")
            # Don't try to reconnect here - let the get_blender_connection handle reconnection
            # Just invalidate the current socket so it will be recreated next time
            self.sock = None
            raise Exception("Timeout waiting for Blender response - try simplifying your request. If Blender is running headless (blender -b), commands never execute; run Blender with a GUI or via 'xvfb-run -a blender' instead")
        except (ConnectionError, BrokenPipeError, ConnectionResetError) as e:
            logger.error(f"Socket connection error: {str(e)}")
            self.sock = None
            raise Exception(f"Connection to Blender lost: {str(e)}")
        except json.JSONDecodeError as e:
            logger.error(f"Invalid JSON response from Blender: {str(e)}")
            raise Exception(f"Invalid response from Blender: {str(e)}")
        except InvalidTokenError:
            # Propagate unwrapped so the caller can try the next token source.
            # The socket itself is healthy (the addon answered) - keep it.
            raise
        except Exception as e:
            logger.error(f"Error communicating with Blender: {str(e)}")
            # Don't try to reconnect here - let the get_blender_connection handle reconnection
            self.sock = None
            raise Exception(f"Communication error with Blender: {str(e)}")


@asynccontextmanager
async def server_lifespan(server: FastMCP) -> AsyncIterator[dict[str, Any]]:
    """Manage server startup and shutdown lifecycle"""
    # We don't need to create a connection here since we're using the global connection
    # for resources and tools

    try:
        # Just log that we're starting up
        logger.info("BlenderMCP server starting up")

        # Try to connect to Blender on startup to verify it's available
        try:
            # This will initialize the global connection if needed
            blender = get_blender_connection()
            logger.info("Successfully connected to Blender on startup")
        except Exception as e:
            logger.warning(f"Could not connect to Blender on startup: {str(e)}")
            logger.warning("Make sure the Blender addon is running before using Blender resources or tools")

        # Return an empty context - we're using the global connection
        yield {}
    finally:
        # Clean up the global connection on shutdown
        global _blender_connection
        if _blender_connection:
            logger.info("Disconnecting from Blender on shutdown")
            _blender_connection.disconnect()
            _blender_connection = None
        logger.info("BlenderMCP server shut down")

# Create the MCP server with lifespan support
mcp = FastMCP(
    "BlenderMCP",
    lifespan=server_lifespan
)

