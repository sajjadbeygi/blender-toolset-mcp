# Global connection for resources (since resources can't access context)
_blender_connection = None
_connection_lock = threading.Lock()

# Poly Haven status cache (Epic 4): refreshed only by the status tool, with a
# short TTL, so get_blender_connection stays free of side effects.
_polyhaven_enabled = False
_polyhaven_status_checked_at = 0.0
_polyhaven_status_message = ""
_POLYHAVEN_STATUS_TTL = 30.0


def refresh_polyhaven_status():
    global _polyhaven_enabled, _polyhaven_status_checked_at, _polyhaven_status_message
    conn = get_blender_connection()
    result = conn.send_command("get_polyhaven_status")
    _polyhaven_enabled = result.get("enabled", False)
    _polyhaven_status_message = result.get("message", "")
    _polyhaven_status_checked_at = time.time()


# Auth-token resolution (BLENDERMCP_TOKEN env override -> MCP-side cache ->
# addon temp file) and the per-user token cache live in ``blender_mcp.token_store``
# (free of any mcp dependency, unit-tested separately).


def get_blender_connection():
    """Get or create a persistent Blender connection (double-checked + serialized)."""
    global _blender_connection

    # Existing connection: verify liveness with a cheap, side-effect-free ping.
    if _blender_connection is not None:
        try:
            _blender_connection.send_command("ping")
            return _blender_connection
        except Exception as e:
            logger.warning(f"Existing connection is no longer valid: {str(e)}")
            try:
                _blender_connection.disconnect()
            except Exception:
                pass
            _blender_connection = None

    with _connection_lock:
        # Double-checked: another thread may have created it while we waited.
        if _blender_connection is not None:
            return _blender_connection

        host = os.getenv("BLENDER_HOST", DEFAULT_HOST)
        port = int(os.getenv("BLENDER_PORT", DEFAULT_PORT))
        conn = BlenderConnection(host=host, port=port)
        if not conn.connect():
            logger.error("Failed to connect to Blender")
            raise Exception("Could not connect to Blender. Make sure the Blender addon is running.")

        # Try every token source in priority order (BLENDERMCP_TOKEN ->
        # BLENDERMCP_TOKEN_FILE -> MCP cache -> addon temp file; empty and
        # placeholder values are skipped by token_store). A candidate the
        # addon rejects does not abort the attempt: we fall through to the
        # next source, ending with zero-config loopback pairing.
        authenticated = False
        for label, candidate in token_store.token_candidates(host, port):
            conn.token = candidate
            try:
                conn.send_command("ping")
                authenticated = True
                logger.info(f"Authenticated using token from {label}")
                break
            except InvalidTokenError:
                logger.warning(f"Token from {label} was rejected - trying next source")

        if not authenticated:
            conn.token = None
            # The addon honors pairing only before its first authenticated
            # client and only for loopback peers: a safe first-time bootstrap.
            paired_token = conn.request_pair_token()
            if paired_token:
                conn.token = paired_token
                logger.info("Obtained auth token via socket pairing")
                try:
                    conn.send_command("ping")
                    authenticated = True
                except Exception as e:  # noqa: BLE001
                    logger.warning(f"Post-pairing ping failed: {e}")
            else:
                logger.warning(
                    "No valid auth token found and socket pairing unavailable - "
                    "commands will fail until the token matches (set BLENDERMCP_TOKEN "
                    "or press 'Reset token & re-pair' in the addon)"
                )

        _blender_connection = conn
        logger.info("Created new persistent connection to Blender")

    return _blender_connection


